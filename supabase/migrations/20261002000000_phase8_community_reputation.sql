CREATE OR REPLACE FUNCTION public.handle_received_like_reputation()
RETURNS trigger AS $$
DECLARE
  v_author_id uuid;
BEGIN
  SELECT author_id INTO v_author_id FROM public.posts WHERE id = NEW.post_id;
  IF v_author_id IS NOT NULL AND v_author_id <> NEW.user_id THEN
    PERFORM public.apply_reputation_event(v_author_id, 'POST_LIKE_RECEIVED', NEW.post_id::text || ':' || NEW.user_id::text, 1, 0, 0, 0, 1);
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = '';

DROP TRIGGER IF EXISTS trg_received_like_reputation ON public.post_likes;
CREATE TRIGGER trg_received_like_reputation AFTER INSERT ON public.post_likes
FOR EACH ROW EXECUTE FUNCTION public.handle_received_like_reputation();

