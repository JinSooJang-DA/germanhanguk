-- Guide rewards are intentionally exposed only through this authenticated RPC.
-- The UI should call it only after a meaningful read signal, never on page load.
CREATE OR REPLACE FUNCTION public.reward_guide_read(p_guide_slug text)
RETURNS boolean AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_inserted_count integer := 0;
BEGIN
  IF v_user_id IS NULL OR nullif(trim(p_guide_slug), '') IS NULL THEN RETURN false; END IF;

  INSERT INTO public.guide_read_rewards (user_id, guide_slug)
  VALUES (v_user_id, trim(p_guide_slug))
  ON CONFLICT (user_id, guide_slug) DO NOTHING;
  GET DIAGNOSTICS v_inserted_count = ROW_COUNT;

  IF v_inserted_count > 0 THEN
    PERFORM public.apply_reputation_event(v_user_id, 'GUIDE_FIRST_READ', trim(p_guide_slug), 1, 0, 1, 0, 0);
    RETURN true;
  END IF;
  RETURN false;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = '';

REVOKE ALL ON FUNCTION public.reward_guide_read(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.reward_guide_read(text) TO authenticated;

