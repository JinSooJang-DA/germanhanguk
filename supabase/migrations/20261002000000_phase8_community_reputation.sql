-- Guide rewards are intentionally exposed only through this authenticated RPC.
-- The UI should call it only after a meaningful read signal, never on page load.
CREATE OR REPLACE FUNCTION public.reward_guide_read(p_guide_slug text)
RETURNS boolean AS $$
DECLARE
  v_user_id uuid := auth.uid();
  v_inserted_count integer := 0;
BEGIN
  IF v_user_id IS NULL OR nullif(trim(p_guide_slug), '') IS NULL THEN RETURN false; END IF;

  INSERT INTO public.guide_read_rewards (user_id, guide_slug)
  VALUES (v_user_id, trim(p_guide_slug))
  ON CONFLICT (user_id, guide_slug) DO NOTHING;
  GET DIAGNOSTICS v_inserted_count = ROW_COUNT;

  IF v_inserted_count > 0 THEN
    PERFORM public.apply_reputation_event(v_user_id, 'GUIDE_FIRST_READ', trim(p_guide_slug), 1, 0, 1, 0, 0);
    RETURN true;
  END IF;
  RETURN false;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = '';

REVOKE ALL ON FUNCTION public.reward_guide_read(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.reward_guide_read(text) TO authenticated;

CREATE OR REPLACE FUNCTION public.get_public_community_identity(p_user_id uuid)
RETURNS TABLE (
  reputation_xp integer, tenure_value integer, tenure_unit text,
  activity_score integer, knowledge_score integer, communication_score integer, helpful_score integer,
  show_community_level boolean, show_germany_tenure boolean, show_reputation_stats boolean
) AS $$
BEGIN
  RETURN QUERY
  SELECT
    CASE WHEN p.show_community_level THEN COALESCE(r.reputation_xp, 0) ELSE NULL END,
    CASE WHEN p.show_germany_tenure AND d.germany_since IS NOT NULL AND d.germany_since <= current_date THEN
      CASE WHEN current_date - d.germany_since < 31 THEN current_date - d.germany_since + 1
           WHEN EXTRACT(YEAR FROM age(current_date, d.germany_since)) < 1 THEN GREATEST(1, EXTRACT(MONTH FROM age(current_date, d.germany_since))::integer)
           ELSE EXTRACT(YEAR FROM age(current_date, d.germany_since))::integer END ELSE NULL END,
    CASE WHEN p.show_germany_tenure AND d.germany_since IS NOT NULL AND d.germany_since <= current_date THEN
      CASE WHEN current_date - d.germany_since < 31 THEN 'day'
           WHEN EXTRACT(YEAR FROM age(current_date, d.germany_since)) < 1 THEN 'month' ELSE 'year' END ELSE NULL END,
    CASE WHEN p.show_reputation_stats THEN COALESCE(r.activity_score, 0) ELSE NULL END,
    CASE WHEN p.show_reputation_stats THEN COALESCE(r.knowledge_score, 0) ELSE NULL END,
    CASE WHEN p.show_reputation_stats THEN COALESCE(r.communication_score, 0) ELSE NULL END,
    CASE WHEN p.show_reputation_stats THEN COALESCE(r.helpful_score, 0) ELSE NULL END,
    p.show_community_level, p.show_germany_tenure, p.show_reputation_stats
  FROM public.profiles p
  LEFT JOIN public.profile_private_details d ON d.user_id = p.id
  LEFT JOIN public.community_reputation r ON r.user_id = p.id
  WHERE p.id = p_user_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = '';
REVOKE ALL ON FUNCTION public.get_public_community_identity(uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_public_community_identity(uuid) TO anon, authenticated;

-- Exact Germany start dates and hidden score totals remain behind RLS; public clients receive privacy-filtered RPC output only.
-- Existing users start at zero. Historical posts/comments are not backfilled.

-- Batch form used by community lists/comments to avoid one RPC per author.
CREATE OR REPLACE FUNCTION public.get_public_community_identities(p_user_ids uuid[])
RETURNS TABLE (
  user_id uuid, reputation_xp integer, tenure_value integer, tenure_unit text,
  show_community_level boolean, show_germany_tenure boolean
) AS $$
  SELECT p.id,
    CASE WHEN p.show_community_level THEN COALESCE(r.reputation_xp, 0) ELSE NULL END,
    CASE WHEN p.show_germany_tenure AND d.germany_since IS NOT NULL AND d.germany_since <= current_date THEN
      CASE WHEN current_date - d.germany_since < 31 THEN current_date - d.germany_since + 1
           WHEN EXTRACT(YEAR FROM age(current_date, d.germany_since)) < 1 THEN GREATEST(1, EXTRACT(MONTH FROM age(current_date, d.germany_since))::integer)
           ELSE EXTRACT(YEAR FROM age(current_date, d.germany_since))::integer END ELSE NULL END,
    CASE WHEN p.show_germany_tenure AND d.germany_since IS NOT NULL AND d.germany_since <= current_date THEN
      CASE WHEN current_date - d.germany_since < 31 THEN 'day'
           WHEN EXTRACT(YEAR FROM age(current_date, d.germany_since)) < 1 THEN 'month' ELSE 'year' END ELSE NULL END,
    p.show_community_level, p.show_germany_tenure
  FROM public.profiles p
  LEFT JOIN public.profile_private_details d ON d.user_id = p.id
  LEFT JOIN public.community_reputation r ON r.user_id = p.id
  WHERE p.id = ANY(p_user_ids);
$$ LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '';
REVOKE ALL ON FUNCTION public.get_public_community_identities(uuid[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_public_community_identities(uuid[]) TO anon, authenticated;
