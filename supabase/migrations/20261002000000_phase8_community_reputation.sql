CREATE OR REPLACE FUNCTION public.apply_reputation_event(
  p_user_id uuid,
  p_event_type text,
  p_source_key text,
  p_xp integer DEFAULT 0,
  p_activity integer DEFAULT 0,
  p_knowledge integer DEFAULT 0,
  p_communication integer DEFAULT 0,
  p_helpful integer DEFAULT 0
) RETURNS boolean AS $$
DECLARE
  v_inserted_count integer := 0;
  v_daily_count integer := 0;
  v_daily_limit integer := CASE p_event_type
    WHEN 'POST_CREATED' THEN 5
    WHEN 'COMMENT_CREATED' THEN 20
    WHEN 'POST_LIKE_RECEIVED' THEN 30
    WHEN 'GUIDE_FIRST_READ' THEN 10
    ELSE NULL
  END;
BEGIN
  IF v_daily_limit IS NOT NULL THEN
    SELECT count(*) INTO v_daily_count
    FROM public.reputation_events
    WHERE user_id = p_user_id
      AND event_type = p_event_type
      AND created_at >= date_trunc('day', now());
    IF v_daily_count >= v_daily_limit THEN RETURN false; END IF;
  END IF;

  INSERT INTO public.reputation_events (
    user_id, event_type, source_key, xp_delta, activity_delta,
    knowledge_delta, communication_delta, helpful_delta
  ) VALUES (
    p_user_id, p_event_type, p_source_key, p_xp, p_activity,
    p_knowledge, p_communication, p_helpful
  ) ON CONFLICT (user_id, event_type, source_key) DO NOTHING;

  GET DIAGNOSTICS v_inserted_count = ROW_COUNT;

  IF v_inserted_count > 0 THEN
    INSERT INTO public.community_reputation (
      user_id, reputation_xp, activity_score, knowledge_score, communication_score, helpful_score
    ) VALUES (p_user_id, GREATEST(0, p_xp), GREATEST(0, p_activity), GREATEST(0, p_knowledge), GREATEST(0, p_communication), GREATEST(0, p_helpful))
    ON CONFLICT (user_id) DO UPDATE SET
      reputation_xp = GREATEST(0, public.community_reputation.reputation_xp + p_xp),
      activity_score = GREATEST(0, public.community_reputation.activity_score + p_activity),
      knowledge_score = GREATEST(0, public.community_reputation.knowledge_score + p_knowledge),
      communication_score = GREATEST(0, public.community_reputation.communication_score + p_communication),
      helpful_score = GREATEST(0, public.community_reputation.helpful_score + p_helpful),
      updated_at = now();
  END IF;
  RETURN v_inserted_count > 0;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = '';

REVOKE ALL ON FUNCTION public.apply_reputation_event(uuid,text,text,integer,integer,integer,integer,integer) FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION public.handle_post_reputation()
RETURNS trigger AS $$
BEGIN
  IF NEW.author_id IS NOT NULL THEN
    PERFORM public.apply_reputation_event(NEW.author_id, 'POST_CREATED', NEW.id::text, 3, 3, 0, 0, 0);
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = '';

DROP TRIGGER IF EXISTS trg_post_reputation ON public.posts;
CREATE TRIGGER trg_post_reputation AFTER INSERT ON public.posts
FOR EACH ROW EXECUTE FUNCTION public.handle_post_reputation();

